"""Golden digests for both V3.0 label generators.

Code comments tell a maintainer that changing the join, the tie-break, the
fallback or the line format means bumping `_GENERATION_VERSION`. Nothing else
enforces that: the manifest notices a *changed version*, never a changed
*generator*. These digests are what fail when the output moves.

A failure here is not automatically a bug. It means the generated bytes changed:
confirm that was intended, bump the model's `_GENERATION_VERSION` so every cached
directory regenerates, then update the digests and the version below.

The digests are the same on every platform, which is the point of writing the
files with an explicit newline: a checksum that differed per operating system
would make the manifest unportable and this test unrunnable off Windows.
"""

import hashlib
from pathlib import Path
from types import ModuleType

import pytest

import birdnet.acoustic.models.v3_0.model as acoustic_model
import birdnet.geo.models.v3_0.model as geo_model
from birdnet.globals import ENV_VAR_APP_DATA
from birdnet.utils.label_manifest import LabelInput, read_manifest, sha256_bytes

# Deliberately small and hand-written: one localized name, one blank cell falling
# back to English, one species missing from the taxonomy entirely.
_TAXONOMY = (
  b"species_code,sci_name,com_name,common_name_de\n"
  b"code1,Scivia one,Robin US,Rotkehlchen\n"
  b"code2,Scivia two,Sparrow US,\n"
)
_GEO_LABELS = (
  b"code1\tScivia one\tRobin\ncode2\tScivia two\tSparrow\ncode9\tScivia nine\tEagle\n"
)
# The acoustic label file carries its own names: one localized, one blank cell
# falling back to English, and for the regional pt_PT one blank cell falling back
# to pt. The last three rows are what the parser rewrites: an underscore in a
# name, a class without a common name, one without a scientific name.
_ACOUSTIC_LABELS = (
  b"ix,birdnet_id,scientific_name,common_name,common_name_de,"
  b"common_name_pt,common_name_pt_PT\n"
  b"0,BN1,Scivia one,Robin,Rotkehlchen,Pisco,Pisco-de-peito-ruivo\n"
  b"1,BN2,Scivia two,Sparrow,,Pardal,\n"
  b"2,BN3,Sound_(event),Sound_(event),,,\n"
  b"3,BN4,Scivia ten,,,,\n"
  b"4,BN5,,Noise,,,\n"
)


def _digest(path: Path) -> str:
  return hashlib.sha256(path.read_bytes()).hexdigest()


def _assert_recorded(
  lang_dir: Path, generator: str, version: int, languages: dict[str, str]
) -> None:
  manifest = read_manifest(lang_dir)
  assert manifest is not None
  assert manifest["generator"] == generator
  assert manifest["generator_version"] == version
  assert manifest["languages"] == languages


def _prepare(
  monkeypatch: pytest.MonkeyPatch,
  module: ModuleType,
  tmp_path: Path,
  labels: bytes,
  languages: dict[str, str],
) -> Path:
  lang_dir = tmp_path / "labels"

  monkeypatch.setenv(ENV_VAR_APP_DATA, str(tmp_path))
  monkeypatch.setattr(module, "_LABELS_DL_SIZE", len(labels))
  monkeypatch.setattr(module, "_LABELS_DL_SHA256", sha256_bytes(labels))
  raw = module._labels_raw_path()
  raw.parent.mkdir(parents=True)
  raw.write_bytes(labels)
  monkeypatch.setattr(module, "_LANGUAGE_TO_COLUMN", languages)
  return lang_dir


def _use_taxonomy(
  monkeypatch: pytest.MonkeyPatch, module: ModuleType, tmp_path: Path
) -> None:
  taxonomy = tmp_path / "taxonomy.csv"
  taxonomy.write_bytes(_TAXONOMY)
  monkeypatch.setattr(
    module,
    "get_taxonomy_v3_input",
    lambda: LabelInput(
      path=taxonomy,
      url="https://example.test/taxonomy.csv",
      size=len(_TAXONOMY),
      sha256=sha256_bytes(_TAXONOMY),
    ),
  )


@pytest.mark.no_tf
def test_geo_generated_bytes_are_unchanged(
  tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
  languages = {"en_us": "com_name", "de": "common_name_de"}
  lang_dir = _prepare(monkeypatch, geo_model, tmp_path, _GEO_LABELS, languages)
  _use_taxonomy(monkeypatch, geo_model, tmp_path)

  class _D(geo_model.GeoDownloaderBaseV3_0):
    @classmethod
    def _get_lang_dir(cls) -> Path:
      return lang_dir

  _D._generate_lang_files()

  assert _digest(lang_dir / "en_us.txt") == (
    "adf11f6f8c5116b6663e7d3df2aafcef26d1298692162f972ed2351931824881"
  )
  assert _digest(lang_dir / "de.txt") == (
    "7eaba39b35a29b40be81bf8141c9bdb0d539ca1b85c06fc562e0675e0daa3c48"
  )
  _assert_recorded(lang_dir, "geo_v3_0", 2, languages)


@pytest.mark.no_tf
def test_acoustic_generated_bytes_are_unchanged(
  tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
  languages = {
    "en_us": "common_name",
    "de": "common_name_de",
    "pt_pt": "common_name_pt_PT",
  }
  lang_dir = _prepare(
    monkeypatch, acoustic_model, tmp_path, _ACOUSTIC_LABELS, languages
  )

  class _D(acoustic_model.AcousticDownloaderBaseV3_0):
    @classmethod
    def _get_lang_dir(cls) -> Path:
      return lang_dir

  _D._generate_lang_files()

  assert _digest(lang_dir / "en_us.txt") == (
    "b40dc7812e31e1303aec5b03374baab43dd6fa87919a47ed0d53082f9ea0106d"
  )
  assert _digest(lang_dir / "de.txt") == (
    "3a711eb9e51c90ed7b370a1c7520cbe34469d206005a409ac48344d067f68714"
  )
  assert _digest(lang_dir / "pt_pt.txt") == (
    "a28a012fcc77ea7108fd14a8c005183d2e5a927f5ececcba85fe75291ffa3f22"
  )
  _assert_recorded(lang_dir, "acoustic_v3_0", 5, languages)
